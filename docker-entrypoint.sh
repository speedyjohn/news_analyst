#!/bin/sh
# Один образ на два процесса: api и worker собираются из одного Dockerfile и
# различаются переменной ROLE. Так сделано потому, что Railway берёт путь к
# railway.json только из настроек сервиса в UI, а через CLI его не задать —
# оба сервиса деплоятся из одного корня и прочитали бы одну и ту же конфигурацию.
# Переменная ROLE решает это без ручных шагов в дашборде.
set -e

case "${ROLE:-api}" in
    api)
        # Миграции применяются на старте api, отдельного шага в деплое нет.
        # Реплика обязана быть одна, иначе несколько процессов полезут в схему разом.
        alembic upgrade head
        # До форка воркеров, а не внутри каждого: иначе на пустой базе три процесса
        # вставляют источники одновременно и двое ловят UniqueViolation.
        python scripts/sync_sources.py
        # Railway подставляет свой $PORT и маршрутизирует приватную сеть только по
        # IPv6, поэтому слушаем [::] — на dual-stack Linux это принимает и IPv4.
        # -t 180: юридический модуль в замерах доходил до 98 с на запрос, дефолтные
        # 30 с gunicorn убивают воркер прямо посреди генерации записки.
        exec gunicorn -b "[::]:${PORT:-8000}" -w 3 -t 180 app.api:app
        ;;
    worker)
        exec python -m app.jobs.scheduler
        ;;
    *)
        echo "Неизвестный ROLE=$ROLE, допустимы api и worker" >&2
        exit 1
        ;;
esac
